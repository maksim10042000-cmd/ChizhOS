#!/bin/sh
#
# ChizhOS — автоматическая подготовка сервера (cloud-init).
#
# Первая строка обязана быть «#!/bin/sh» или «#cloud-config» — этого требует
# поле Cloud-init в панели Timeweb. Поэтому скрипт написан на POSIX sh
# (в Ubuntu это dash), без специфичных для bash конструкций.
#
# Куда вставлять: при создании сервера в Timeweb Cloud, поле «Cloud-init».
# Скрипт выполнится один раз при первой загрузке сервера и сделает всё,
# что описано в разделе 3 инструкции DEPLOY-TIMEWEB.md:
#
#   • обновит систему;
#   • установит Node.js 20, Nginx, Git, SQLite, PM2, Certbot;
#   • создаст отдельного пользователя chizhos (запускать сайт от root небезопасно);
#   • настроит межсетевой экран (откроет только SSH и веб);
#   • создаст файл подкачки 2 ГБ, чтобы сборка не падала из-за нехватки памяти;
#   • подготовит папки /var/www/chizhos, data, logs, backups.
#
# Скрипт НЕ делает (это требует ваших данных и выполняется вручную):
#   • не заполняет .env — там пароль администратора;
#   • не устанавливает зависимости и не собирает проект;
#   • не настраивает домен и HTTPS.
#
# После загрузки сервера подключитесь по SSH и продолжите
# с раздела 4 инструкции DEPLOY-TIMEWEB.md.
#
# Проверить, что скрипт отработал:
#   cat /root/CHIZHOS-NEXT-STEPS.txt
#   tail -30 /var/log/cloud-init-output.log
#

set -e

# ---------------------------------------------------------------------------
# НЕОБЯЗАТЕЛЬНО: адрес вашего Git-репозитория.
# Если заполнить — код проекта скачается автоматически.
# Если оставить пустым — загрузите проект вручную (раздел 4 инструкции).
# Для закрытого репозитория оставьте пустым: скрипт не сможет ввести пароль.
# ---------------------------------------------------------------------------
REPO_URL=""

APP_DIR="/var/www/chizhos"
APP_USER="chizhos"

# Отключаем любые интерактивные вопросы — при автозагрузке отвечать некому.
export DEBIAN_FRONTEND=noninteractive
export NEEDRESTART_MODE=a

echo "===== ChizhOS: подготовка сервера начата ====="
date

# ---------------------------------------------------------------------------
# 1. Обновление системы
# ---------------------------------------------------------------------------
echo "--- 1/7 Обновление системы"
apt-get update -y
apt-get upgrade -y -o Dpkg::Options::="--force-confdef" -o Dpkg::Options::="--force-confold"

# ---------------------------------------------------------------------------
# 2. Node.js 20
# ---------------------------------------------------------------------------
echo "--- 2/7 Установка Node.js 20"
curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
apt-get install -y nodejs

# ---------------------------------------------------------------------------
# 3. Остальные программы
# ---------------------------------------------------------------------------
echo "--- 3/7 Установка Nginx, Git, SQLite, Certbot и утилит"
apt-get install -y nginx git sqlite3 ufw rsync unzip certbot python3-certbot-nginx

# ---------------------------------------------------------------------------
# 4. PM2 — менеджер процессов
# ---------------------------------------------------------------------------
echo "--- 4/7 Установка PM2"
npm install -g pm2

# ---------------------------------------------------------------------------
# 5. Файл подкачки
#    Сборка Next.js требовательна к памяти. На тарифах с 1–2 ГБ RAM
#    без подкачки сборка падает с ошибкой «JavaScript heap out of memory».
# ---------------------------------------------------------------------------
echo "--- 5/7 Создание файла подкачки 2 ГБ"
if [ ! -f /swapfile ]; then
  fallocate -l 2G /swapfile
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
  echo "    файл подкачки создан"
else
  echo "    файл подкачки уже существует, пропускаем"
fi

# ---------------------------------------------------------------------------
# 6. Пользователь приложения и папки
#    Сайт работает не от root: если в приложении найдут уязвимость,
#    злоумышленник не получит полный контроль над сервером.
# ---------------------------------------------------------------------------
echo "--- 6/7 Создание пользователя $APP_USER и папок"
if ! id "$APP_USER" >/dev/null 2>&1; then
  adduser --disabled-password --gecos "" "$APP_USER"
fi

mkdir -p /var/www
chown "$APP_USER:$APP_USER" /var/www

if [ -n "$REPO_URL" ]; then
  echo "    скачивание проекта из $REPO_URL"
  sudo -u "$APP_USER" git clone "$REPO_URL" "$APP_DIR" || \
    echo "    ! не удалось скачать репозиторий — загрузите проект вручную"
fi

# Папки для базы, логов и резервных копий.
sudo -u "$APP_USER" mkdir -p "$APP_DIR/data" "$APP_DIR/logs" "$APP_DIR/backups" 2>/dev/null || {
  mkdir -p "$APP_DIR/data" "$APP_DIR/logs" "$APP_DIR/backups"
  chown -R "$APP_USER:$APP_USER" "$APP_DIR"
}

# ---------------------------------------------------------------------------
# 7. Межсетевой экран
#    Открыты только SSH (управление) и веб (80/443).
#    Порт 3000, на котором работает приложение, снаружи закрыт —
#    к нему обращается только Nginx изнутри сервера.
# ---------------------------------------------------------------------------
echo "--- 7/7 Настройка межсетевого экрана"
ufw allow OpenSSH
ufw allow 'Nginx Full'
ufw --force enable

# ---------------------------------------------------------------------------
# Итог
# ---------------------------------------------------------------------------
NODE_V=$(node -v 2>/dev/null || echo "не установлен")
NPM_V=$(npm -v 2>/dev/null || echo "не установлен")
PM2_V=$(pm2 -v 2>/dev/null || echo "не установлен")

cat > /root/CHIZHOS-NEXT-STEPS.txt <<EOF
========================================
 ChizhOS — сервер подготовлен
========================================

Установлено:
  Node.js  $NODE_V
  npm      $NPM_V
  PM2      $PM2_V
  Nginx, Git, SQLite3, Certbot, UFW
  Файл подкачки 2 ГБ

Создано:
  пользователь: $APP_USER
  папка проекта: $APP_DIR
  подпапки: data, logs, backups

Межсетевой экран: открыты SSH, HTTP (80), HTTPS (443)

----------------------------------------
ЧТО ДЕЛАТЬ ДАЛЬШЕ
----------------------------------------
Раздел 3 инструкции DEPLOY-TIMEWEB.md можно ПРОПУСТИТЬ — он уже выполнен.

Начните с раздела 4 «Загрузка проекта»:

 1. Загрузите файлы проекта в $APP_DIR
 2. Создайте файл настроек:
      cd $APP_DIR && sudo -u $APP_USER cp .env.example .env
      sudo -u $APP_USER nano $APP_DIR/.env
      (задайте свой ADMIN_PASSWORD и ORG_NAME)
 3. Установите зависимости:
      cd $APP_DIR && sudo -u $APP_USER npm ci
 4. Создайте базу и администратора:
      cd $APP_DIR && sudo -u $APP_USER npx prisma migrate deploy
      cd $APP_DIR && sudo -u $APP_USER npx prisma generate
      cd $APP_DIR && sudo -u $APP_USER npm run create-admin
 5. Соберите и запустите:
      cd $APP_DIR && sudo -u $APP_USER npm run build
      cd $APP_DIR && sudo -u $APP_USER pm2 start ecosystem.config.js
      sudo -u $APP_USER pm2 save
 6. Настройте Nginx (раздел 11 инструкции)

Журнал этой установки: /var/log/cloud-init-output.log
EOF

# Показать подсказку при каждом входе на сервер.
cat > /etc/profile.d/chizhos-hint.sh <<'HINT'
if [ -f /root/CHIZHOS-NEXT-STEPS.txt ] && [ "$(id -u)" = "0" ]; then
  echo ""
  echo "ChizhOS: сервер подготовлен. Дальнейшие шаги — cat /root/CHIZHOS-NEXT-STEPS.txt"
  echo ""
fi
HINT
chmod +x /etc/profile.d/chizhos-hint.sh

echo "===== ChizhOS: подготовка сервера завершена ====="
cat /root/CHIZHOS-NEXT-STEPS.txt
date
